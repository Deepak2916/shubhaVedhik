/**
 * Generates supabase/seed.sql from the template presets.
 *   npm run seed:generate
 * Validates every preset with the same Zod schemas the app uses, so a broken
 * preset fails here instead of in production.
 */
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { invitationDataSchema } from '../src/lib/validation/invitation.ts'
import { sectionDefSchema, templateConfigSchema } from '../src/lib/validation/template.ts'
import { LIBRARY_TRACKS, TEMPLATE_CATEGORIES, TEMPLATE_PRESETS } from '../src/features/templates/presets/presets.ts'

const uuid = (seed: string) => {
  const h = createHash('sha256').update(`shubhavedhik:${seed}`).digest('hex')
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`
}
const lit = (v: string | null | undefined) => (v == null ? 'null' : `'${v.replaceAll("'", "''")}'`)
const json = (v: unknown) => {
  const s = JSON.stringify(v)
  if (s.includes('$j$')) throw new Error('JSON contains dollar-quote delimiter')
  return `$j$${s}$j$::jsonb`
}
const arr = (v: string[]) => `array[${v.map(lit).join(',')}]::text[]`

const out: string[] = [
  '-- =====================================================================',
  '-- GENERATED by scripts/generate-seed.ts — do not edit by hand.',
  '-- Demo catalogue: categories, music library, six launch templates.',
  '-- Idempotent: safe to run more than once.',
  '-- =====================================================================',
  '',
  'begin;',
  '',
  '-- categories',
]

TEMPLATE_CATEGORIES.forEach((c, i) => {
  out.push(
    `insert into public.template_categories (id, slug, name, description, position) values (${lit(uuid('cat:' + c.slug))}, ${lit(c.slug)}, ${lit(c.name)}, ${lit(c.description)}, ${i}) on conflict (slug) do nothing;`,
  )
})

out.push('', '-- platform music library (bundled, royalty-free, generated for this project)')
LIBRARY_TRACKS.forEach((t) => {
  out.push(
    `insert into public.template_media (id, template_id, kind, title, description, public_url, mime_type, meta) values (${lit(uuid('track:' + t.url))}, null, 'audio', ${lit(t.title)}, ${lit(t.description)}, ${lit(t.url)}, 'audio/mpeg', '{"bundled":true}'::jsonb) on conflict (id) do nothing;`,
  )
})

TEMPLATE_PRESETS.forEach((p, i) => {
  const config = templateConfigSchema.parse(p.config)
  const sections = p.sections.map((s) => sectionDefSchema.parse(s))
  const sample = invitationDataSchema.parse(p.sample)
  const tid = uuid('tpl:' + p.slug)
  const vid = uuid('ver:' + p.slug + ':1')
  out.push(
    '',
    `-- ${p.name} (${p.slug})`,
    `do $seed$ begin`,
    `if not exists (select 1 from public.invitation_templates where slug = ${lit(p.slug)}) then`,
    `  insert into public.invitation_templates (id, slug, name, tagline, description, category_id, cultural_tags, languages, cover_image_url, preview_images, supports_music, supports_video, supports_gallery, status, is_featured, position, sample_data)`,
    `  values (${lit(tid)}, ${lit(p.slug)}, ${lit(p.name)}, ${lit(p.tagline)}, ${lit(p.description)}, (select id from public.template_categories where slug = ${lit(p.category)}), ${arr(p.culturalTags)}, ${arr(p.languages)}, ${lit(p.coverImage)}, ${arr(p.previewImages)}, true, ${sections.some((s) => s.type === 'videos')}, true, 'published', ${p.featured}, ${i}, ${json(sample)});`,
    `  insert into public.template_versions (id, template_id, version, status, config, changelog)`,
    `  values (${lit(vid)}, ${lit(tid)}, 1, 'draft', ${json(config)}, 'Launch version');`,
  )
  sections.forEach((s, pos) => {
    out.push(
      `  insert into public.template_sections (version_id, section_key, type, position, enabled, config) values (${lit(vid)}, ${lit(s.key)}, ${lit(s.type)}, ${pos}, ${s.enabled}, ${json(s.config)});`,
    )
  })
  out.push(
    `  update public.template_versions set status = 'published', published_at = now() where id = ${lit(vid)};`,
    `  update public.invitation_templates set current_version_id = ${lit(vid)} where id = ${lit(tid)};`,
    `end if;`,
    `end $seed$;`,
  )
})

out.push(
  '',
  '-- public platform settings',
  `insert into public.platform_settings (key, value, is_public) values ('site.name', '"ShubhaVedhik"'::jsonb, true) on conflict (key) do nothing;`,
  `insert into public.platform_settings (key, value, is_public) values ('site.support_email', '"hello@example.com"'::jsonb, true) on conflict (key) do nothing;`,
  `insert into public.platform_settings (key, value, is_public) values ('limits.max_photos', '60'::jsonb, true) on conflict (key) do nothing;`,
  `insert into public.platform_settings (key, value, is_public) values ('limits.max_videos', '6'::jsonb, true) on conflict (key) do nothing;`,
  '',
  'commit;',
  '',
)

const target = fileURLToPath(new URL('../supabase/seed.sql', import.meta.url))
writeFileSync(target, out.join('\n'))
console.log(`Wrote ${target} (${TEMPLATE_PRESETS.length} templates)`)
